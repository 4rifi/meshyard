export type Prop = Exclude<keyof typeof maps, 'agent'>;
const colours: Record<string, PixelColour> = {
  l: 'line',
  m: 'muted',
  d: 'deep',
  p: 'path',
  w: 'wood',
  c: 'codex',
  o: 'ok',
  k: 'text',
  r: 'danger',
  g: 'grassDark',
  t: 'text',
};
export function pixelSprite(
  prop: Prop | 'agent',
  x: number,
  y: number,
  kind?: AgentKind,
): Graphics {
  const drawing = new Graphics();
  maps[prop].forEach((row, py) => {
    for (let px = 0; px < row.length; px += 1) {
      const pixel = row.charAt(px);
      const colour =
        pixel === 'a'
          ? kind === 'Codex'
            ? 'codex'
            : 'claude'
          : colours[pixel];
      if (colour) drawing.rect(x + px, y + py, 1, 1).fill(ink[colour]);
    }
  });
  return drawing;
}
